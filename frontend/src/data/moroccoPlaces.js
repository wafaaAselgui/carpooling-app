// Fuzzy matching utility (ignores accents, casing, and spaces)
export const normalizeCityName = (str) => {
  if (!str) return "";
  return str
    .trim()
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[-_'\s]/g, "");
};

export const findPlaceCoords = (name) => {
  if (!name) return null;
  const target = normalizeCityName(name);
  const found = MOROCCO_PLACES.find((p) => normalizeCityName(p.name) === target);
  return found ? found.coords : null;
};


// Si la ville n'est pas dans la liste statique, on résout ses coordonnées en ligne
const geocodeCache = new Map();

export async function resolvePlaceCoords(cityName) {
    if (!cityName) return null;
    const staticCoords = findPlaceCoords(cityName);
    if (staticCoords) return staticCoords;

    const normalized = normalizeCityName(cityName);
    if (geocodeCache.has(normalized)) return geocodeCache.get(normalized);

    try {
        const res = await fetch(
            `https://nominatim.openstreetmap.org/search?q=${encodeURIComponent(
                cityName + ", Maroc"
            )}&format=json&limit=1`
        );
        const data = await res.json();
        if (data && data[0]) {
            const coords = [parseFloat(data[0].lat), parseFloat(data[0].lon)];
            geocodeCache.set(normalized, coords);
            return coords;
        }
    } catch (e) {
        console.warn("Échec geocoding pour:", cityName);
    }
    return null;
}